def fmt(p: Published, key: str) -> str:
    """Число так, как оно записано в источнике: запятая, тот же знак после неё; нет значения — прочерк."""
    v = p.values.get(key)
    return "—" if v is None else f"{v:.{p.nd}f}".replace(".", ",")


